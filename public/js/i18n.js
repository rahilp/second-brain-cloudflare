const I18N_CATALOGS = { en: I18N_EN, it: I18N_IT }

let currentLocale = 'en'

function resolveI18nPath(messages, path) {
  const parts = String(path).split('.')
  let node = messages
  for (const part of parts) {
    if (node == null || typeof node !== 'object') return undefined
    node = node[part]
  }
  return typeof node === 'string' ? node : node
}

function interpolate(raw, params) {
  if (!params) return raw
  return raw.replace(/\{(\w+)\}/g, (_, key) =>
    params[key] != null ? String(params[key]) : `{${key}}`,
  )
}

/** Translate a dotted key. Optional `{name}` placeholders. */
function t(path, params) {
  let node = resolveI18nPath(I18N_CATALOGS[currentLocale], path)
  if (node == null) node = resolveI18nPath(I18N_CATALOGS.en, path)
  if (typeof node !== 'string') return path
  return interpolate(node, params)
}

/** Plural helper: path.one / path.other with `{n}`. */
function tPlural(path, n, params) {
  const count = Number(n) || 0
  const key = count === 1 ? `${path}.one` : `${path}.other`
  return t(key, { n: String(count), ...(params || {}) })
}

function getLocale() {
  return currentLocale
}

function localeTag() {
  return currentLocale === 'it' ? 'it-IT' : 'en-US'
}

/**
 * UI-only dates. Do not use for LLM/chat payload serialization.
 *
 * toLocaleDateString forces a date onto the output even when `options` asks
 * for time fields only (year/month/day default to "numeric" behind the
 * scenes), so a caller wanting just a clock time gets "9/9/2026, 3:48 PM"
 * instead of "3:48 PM". Routed through toLocaleTimeString in that one case;
 * every other combination (date alone, or date plus time) is unaffected.
 */
function formatDateUI(value, options) {
  const d = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(d.getTime())) return ''
  const hasDatePart = options && (options.year || options.month || options.day || options.weekday)
  const hasTimePart = options && (options.hour || options.minute || options.second)
  if (hasTimePart && !hasDatePart) return d.toLocaleTimeString(localeTag(), options)
  return d.toLocaleDateString(localeTag(), options)
}

/**
 * Same as formatDateUI, but reads the UTC calendar date rather than the
 * viewer's local one. For values that ARE a calendar date rather than a
 * moment — when_at's date-only case (always midnight UTC; we never store a
 * meaningful time). formatDateUI would read a UTC midnight as the previous
 * day everywhere west of Greenwich, which is exactly the bug this exists to
 * avoid: a due-by date has to read the same regardless of the viewer's
 * timezone, since nothing about "when" it is due is timezone-relative yet.
 */
function formatDateUTC(value, options) {
  const d = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(d.getTime())) return ''
  return new Intl.DateTimeFormat(localeTag(), { ...options, timeZone: 'UTC' }).format(d)
}

function formatNumberUI(n) {
  return Number(n).toLocaleString(localeTag())
}

function readStoredLocale() {
  try {
    const stored = localStorage.getItem(SB_LOCALE_KEY)
    if (stored === 'en' || stored === 'it') return stored
  } catch (_) {
    /* private mode */
  }
  const nav = (typeof navigator !== 'undefined' && navigator.language
    ? navigator.language
    : ''
  ).toLowerCase()
  if (nav.startsWith('it')) return 'it'
  return 'en'
}

function initI18n(forceLocale) {
  currentLocale =
    forceLocale === 'en' || forceLocale === 'it' ? forceLocale : readStoredLocale()
  try {
    localStorage.setItem(SB_LOCALE_KEY, currentLocale)
  } catch (_) {
    /* ignore */
  }
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = currentLocale
  }
  return currentLocale
}

function setLocale(loc) {
  if (loc !== 'en' && loc !== 'it') return
  try {
    localStorage.setItem(SB_LOCALE_KEY, loc)
  } catch (_) {
    /* ignore */
  }
  location.reload()
}

function applyLocale() {
  const loc = getLocale()
  document.querySelectorAll('#locale-toggle [data-locale-val]').forEach((b) =>
    b.classList.toggle('active', b.dataset.localeVal === loc),
  )
}

/**
 * Apply data-i18n / data-i18n-html / data-i18n-attr on elements under root.
 * data-i18n → textContent
 * data-i18n-html → innerHTML (trusted catalog strings only)
 * data-i18n-attr="placeholder|title|aria-label" with data-i18n key on same el
 */
function applyI18nDom(root) {
  const scope = root || document
  if (!scope.querySelectorAll) return
  scope.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n')
    if (!key) return
    const attrList = el.getAttribute('data-i18n-attr')
    if (attrList) {
      const text = t(key)
      attrList.split('|').forEach((attr) => {
        const name = attr.trim()
        if (name) el.setAttribute(name, text)
      })
      return
    }
    if (el.hasAttribute('data-i18n-html')) {
      el.innerHTML = t(key)
    } else {
      el.textContent = t(key)
    }
  })
}
